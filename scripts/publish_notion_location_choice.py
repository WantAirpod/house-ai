def replace_existing_page(notion: Notion, parent_page_id: str, blocks: list[dict]) -> dict:
    notion.request("PATCH", f"pages/{PAGE_ID}", {"archived": False})

    for block in notion.children(parent_page_id):
        if (
            block["type"] == "child_page"
            and block["child_page"].get("title") == PAGE_TITLE
            and block["id"].replace("-", "") != PAGE_ID
        ):
            notion.request("PATCH", f"pages/{block['id']}", {"archived": True})

    for block in notion.children(PAGE_ID):
        endpoint = "pages" if block["type"] == "child_page" else "blocks"
        notion.request("PATCH", f"{endpoint}/{block['id']}", {"archived": True})

    notion.append_children(PAGE_ID, blocks)
    return notion.request("GET", f"pages/{PAGE_ID}")


def main() -> None:
    env = read_env(Path(".env"))
    api_key = env.get("NOTION_API_KEY")
    parent_page_id = env.get("NOTION_PARENT_PAGE_ID")
    if not api_key or not parent_page_id:
        raise SystemExit("NOTION_API_KEY and NOTION_PARENT_PAGE_ID are required")

    notion = Notion(api_key)
    posting_parent_id = ensure_posting_hub(notion, parent_page_id)
    page = replace_existing_page(notion, posting_parent_id, build_blocks())
    rebuild_hub(notion, posting_parent_id)
    print(page["url"])


if __name__ == "__main__":
    main()
