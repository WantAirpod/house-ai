def archive_existing_page(notion: Notion, parent_page_id: str) -> None:
    for block in notion.children(parent_page_id):
        if block["type"] == "child_page" and block["child_page"].get("title") == PAGE_TITLE:
            notion.request("PATCH", f"pages/{block['id']}", {"archived": True})


def main() -> None:
    env = read_env(Path(".env"))
    api_key = env.get("NOTION_API_KEY")
    parent_page_id = env.get("NOTION_PARENT_PAGE_ID")
    if not api_key or not parent_page_id:
        raise SystemExit("NOTION_API_KEY and NOTION_PARENT_PAGE_ID are required")
    notion = Notion(api_key)
    archive_existing_page(notion, parent_page_id)
    page = notion.create_child_page(parent_page_id=parent_page_id, title=PAGE_TITLE, blocks=build_blocks())
    print(page["url"])


if __name__ == "__main__":
    main()
